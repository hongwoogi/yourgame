export function apiErrorMessage(code, locale = 'en', fallback = '') {
  const messages = ERROR_MESSAGES[locale === 'ko' ? 'ko' : 'en'];
  if (typeof code === 'string' && Object.hasOwn(messages, code)) return messages[code];
  return typeof fallback === 'string' && fallback.trim() ? fallback : messages.SERVICE_UNAVAILABLE;
}
